const {chromium}=require('../test-data/ui/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1512,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.MANIALAB_URL||'http://127.0.0.1:8982';await page.goto(base);
 await page.locator('#files').setInputFiles(path.resolve('tests/artifacts/timing-137.wav'));
 await page.waitForFunction(()=>document.querySelector('#projectTitle').textContent==='timing-137');
 await page.locator('#analysisEngine').selectOption('basic');await page.locator('#analyze').click();
 await page.waitForFunction(()=>!document.querySelector('#analyze').disabled,{},{timeout:90000});
 const original=Number(await page.locator('#offset').inputValue());
 await page.locator('#offset').fill(String(original+55));await page.locator('#checkTiming').click();
 await page.waitForFunction(()=>document.querySelector('#timingLocations').textContent.includes('可疑区间'));
 const buttons=page.locator('#timingLocations button'),count=await buttons.count();
 if(!count)throw Error('No navigation for suspect timing sections');
 const target=buttons.nth(Math.min(1,count-1)),label=await target.textContent();await target.click();
 const start=Number(await page.locator('#auditionStart').inputValue());
 if(start!==Number(label.split('–')[0]))throw Error('Wrong audition location '+start+' '+label);
 if(!await page.locator('.audition-panel').evaluate(e=>e.open))throw Error('Audition panel stayed closed');
 await page.locator('#auditionA').click();
 await page.waitForFunction(()=>document.querySelector('#auditionAudio').src.startsWith('blob:'),{},{timeout:30000});
 await page.locator('#auditionAudio').evaluate(a=>a.pause());
 await page.locator('#offset').fill(String(original));
 if((await page.locator('#timingLocations').textContent()).includes('可疑区间'))throw Error('Stale diagnosis survived an offset edit');
 await page.locator('#timingLocations button').filter({hasText:'结尾'}).click();
 const endStart=Number(await page.locator('#auditionStart').inputValue());
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 console.log(JSON.stringify({suspectSections:count,start,endStart,overflow,errors}));
 await browser.close();if(errors.length||overflow)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
