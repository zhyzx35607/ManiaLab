const {chromium}=require('../test-data/ui/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1512,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.MANIALAB_URL||'http://127.0.0.1:8979';await page.goto(base);
 await page.locator('#files').setInputFiles(path.resolve('tests/artifacts/synthetic.wav'));
 await page.waitForFunction(()=>document.querySelector('#projectTitle').textContent==='synthetic');
 await page.locator('#analysisEngine').selectOption('basic');await page.locator('#analyze').click();
 await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('采音候选'),{},{timeout:90000});
 await page.locator('.audition-panel summary').click();
 await page.locator('#auditionStart').fill('1');await page.locator('#offset').fill('91');
 await page.locator('#auditionA').click();
 await page.waitForFunction(()=>document.querySelector('#auditionAudio').currentTime>0,{},{timeout:10000});
 const a=await page.locator('#auditionNote').textContent();
 await page.locator('#auditionOffset').fill('117');await page.locator('#auditionB').click();
 await page.waitForFunction(()=>document.querySelector('#auditionNote').textContent.startsWith('B：'));
 await page.locator('#auditionApply').click();
 if(await page.locator('#offset').inputValue()!=='117')throw Error('B Offset not applied');
 await page.locator('#auditionEvidence').click();
 await page.waitForFunction(()=>document.querySelector('#auditionNote').textContent.startsWith('原始采音'));
 await page.locator('#clicks').check();await page.locator('#releases').check();await page.locator('#metronome').check();
 await page.locator('#audio').evaluate(a=>a.play());await page.waitForTimeout(300);
 if(!await page.locator('#auditionAudio').evaluate(a=>a.paused))throw Error('two music tracks playing');
 await page.locator('#audio').evaluate(a=>{a.currentTime=4;});await page.waitForTimeout(200);
 await page.locator('#audio').evaluate(a=>a.pause());
 await page.screenshot({path:'tests/artifacts/alpha4-audition.png',fullPage:true});
 console.log(JSON.stringify({a,errors}));await browser.close();if(errors.length)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
