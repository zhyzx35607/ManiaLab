const {chromium}=require('../test-data/ui/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1512,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.MANIALAB_URL||'http://127.0.0.1:8982';await page.goto(base);
 await page.locator('#files').setInputFiles(path.resolve('tests/artifacts/synthetic.wav'));
 await page.waitForFunction(()=>document.querySelector('#projectTitle').textContent==='synthetic');
 await page.locator('#analysisEngine').selectOption('basic');await page.locator('#analyze').click();
 await page.waitForFunction(()=>!document.querySelector('#analyze').disabled,{},{timeout:120000});
 const pid=await page.locator('#recent').inputValue();
 const before=await(await page.request.get(base+'/api/projects/'+pid)).json();
 await page.locator('[data-key="6"]').click();
 await page.locator('#bpm').fill('210');await page.locator('#offset').fill('91');await page.locator('#timingConfirmed').check();
 await page.locator('.reference-style summary').click();
 await page.locator('#referenceStyleFile').setInputFiles(path.resolve('tests/artifacts/public-maps/5900981.osu'));
 await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('已套用参考谱'));
 const state=await(await page.request.get(base+'/api/projects/'+pid)).json();
 if(state.settings.keys!==6||state.reference_style.objects!==1850||JSON.stringify(state.analysis)!==JSON.stringify(before.analysis))throw Error('reference changed source or target');
 if(await page.locator('#bpm').inputValue()!=='210'||await page.locator('#offset').inputValue()!=='91'||!await page.locator('#timingConfirmed').isChecked())throw Error('reference discarded timing draft');
 await page.locator('#audioShift').fill('0');await page.locator('#audioShift').dispatchEvent('change');
 await page.locator('#bpm').fill('120');await page.locator('#offset').fill('0');await page.locator('#timingConfirmed').check();
 await page.locator('#generate').click();await page.waitForFunction(()=>!document.querySelector('#generate').disabled,{},{timeout:60000});
 if(await page.locator('#message').evaluate(e=>e.classList.contains('error')))throw Error(await page.locator('#message').textContent());
 const saved=await(await page.request.get(base+'/api/projects/'+pid)).json();
 if(saved.variants[saved.active].audio_shift_ms!==0)throw Error('clock setting not persisted');
 await page.screenshot({path:'tests/artifacts/alpha4-reference-style.png',fullPage:true});
 console.log(JSON.stringify({reference:state.reference_style,keys:state.settings.keys,errors}));
 await browser.close();if(errors.length)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
