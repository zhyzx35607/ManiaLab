const {chromium}=require('../test-data/ui/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1512,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.MANIALAB_URL||'http://127.0.0.1:8980';await page.goto(base);
 await page.waitForFunction(()=>document.querySelector('#analysisEngine').value==='deep');
 await page.locator('#files').setInputFiles(path.resolve('tests/artifacts/synthetic.wav'));
 await page.waitForFunction(()=>document.querySelector('#projectTitle').textContent==='synthetic');
 await page.locator('#analyze').click();
 await page.waitForFunction(()=>!document.querySelector('#analyze').disabled,{},{timeout:240000});
 if(await page.locator('#message').evaluate(e=>e.classList.contains('error')))throw Error(await page.locator('#message').textContent());
 const pid=await page.locator('#recent').inputValue();
 let state=await(await page.request.get(base+'/api/projects/'+pid)).json();
 if(!state.analysis.separation||state.analysis.voices.length!==4)throw Error('missing source evidence');
 if(state.analysis.candidates.length!==5)throw Error('separation residue became a spurious musical candidate');
 const expected=[[1000,3000],[5000,9000],[12000,13000],[20000,23000],[26000,28000]];
 state.analysis.candidates.forEach((n,i)=>{if(Math.abs(n.start-expected[i][0])>20||Math.abs(n.end-expected[i][1])>20)throw Error('source onset/release clock regression');});
 await page.locator('#voice').selectOption('vocals');
 await page.waitForFunction(()=>document.querySelector('#audio').src.includes('/stem/vocals'));
 const stem=await page.request.get(base+`/api/projects/${pid}/stem/vocals`);
 if(stem.status()!==200||!(stem.headers()['content-type']||'').includes('wav'))throw Error('stem not playable');
 await page.locator('#bpm').fill('120');await page.locator('#offset').fill('0');await page.locator('#timingConfirmed').check();
 await page.locator('#generate').click();
 await page.waitForFunction(()=>!document.querySelector('#generate').disabled,{},{timeout:120000});
 state=await(await page.request.get(base+'/api/projects/'+pid)).json();
 if(state.active<0)throw Error(await page.locator('#message').textContent());
 const v=state.variants[state.active];
 if(!v.report.valid||v.report.grid.off_grid)throw Error('invalid generated chart');
 await page.locator('.audition-panel summary').click();
 await page.locator('#auditionChart').click();
 await page.waitForFunction(()=>document.querySelector('#auditionAudio').currentTime>0,{},{timeout:10000});
 await page.screenshot({path:'tests/artifacts/alpha4-deep-workbench.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 console.log(JSON.stringify({engine:state.analysis.engine,voices:state.analysis.voices,notes:v.report.notes,ln:v.report.ln,offGrid:v.report.grid.off_grid,overflow,errors}));
 await browser.close();if(errors.length||overflow)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
